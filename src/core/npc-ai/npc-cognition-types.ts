/**
 * Milestone 92: AI NPC Cognition Contract & Type Definitions
 *
 * Establishes the bounded types for:
 * 1. Bounded Perception (NpcPerception)
 * 2. Structured Memory (NpcMemory)
 * 3. Contextual Goal (NpcGoal)
 * 4. Structured Action Proposal (NpcActionProposal)
 * 5. Cognition Provider Interface (NpcCognitionProvider)
 * 6. AI Runtime Execution Result (NpcAiCycleResult)
 *
 * Invariant: The AI is an intelligent actor that proposes actions.
 * It NEVER directly mutates WorldState, persistence, or authoritative facts.
 */

import type { ActivityState } from '../entities/agent.js';
import type { RestaurantOperationalState } from '../entities/restaurant.js';

/**
 * Valid action types Elena can propose.
 * Intentionally bounded to actions that can be evaluated and mapped to World Core commands.
 */
export type NpcActionType =
  | 'observe'
  | 'offer_service'
  | 'approach_player'
  | 'acknowledge_player';

/**
 * Memory types an NPC can retain across runtime cycles.
 */
export type NpcMemoryType =
  | 'service_accepted'
  | 'service_offered'
  | 'player_observed'
  | 'greeting_exchanged';

/**
 * Structured, bounded memory entry.
 * Completely distinct from authoritative World History.
 */
export interface NpcMemory {
  readonly id: string;
  readonly timestamp: string;
  readonly type: NpcMemoryType;
  readonly summary: string;
  readonly targetAgentId?: string;
  readonly establishmentId?: string;
}

/**
 * Operational goal for the NPC.
 */
export interface NpcGoal {
  readonly goalId: string;
  readonly description: string;
  readonly priority: number;
}

/**
 * Read-only perception projection of a perceived co-located player.
 * Minimal and bounded: does not expose private balances, player activities, or secrets.
 */
export interface PerceivedPlayerSummary {
  readonly id: string;
  readonly name: string;
  readonly locationId: string;
  readonly interiorSpaceId: string | null;
  readonly isCoLocated: boolean;
  readonly hasActiveService: boolean;
}

/**
 * Read-only perception projection of the NPC's assigned establishment.
 */
export interface PerceivedEstablishmentSummary {
  readonly id: string;
  readonly name: string;
  readonly operationalState: RestaurantOperationalState;
  readonly isAttendantAssigned: boolean;
}

/**
 * Complete bounded perception for an NPC.
 * Contains only what the NPC is legitimately allowed to perceive.
 */
export interface NpcPerception {
  readonly agentId: string;
  readonly agentName: string;
  readonly role: string;
  readonly locationId: string;
  readonly interiorSpaceId: string | null;
  readonly activityState: ActivityState;
  readonly worldTime: string;
  readonly civilTime: {
    readonly hour: number;
    readonly minute: number;
    readonly isoCivilString: string;
    readonly timeZone: string;
  };
  readonly isOnDutyShift: boolean;
  readonly establishment: PerceivedEstablishmentSummary | null;
  readonly perceivedPlayer: PerceivedPlayerSummary | null;
  readonly activeService: {
    readonly playerId: string;
    readonly establishmentId: string;
    readonly worldTime: string;
  } | null;
  readonly recentMemories: readonly NpcMemory[];
}

/**
 * Structured action proposal generated by AI cognition.
 * AI proposal != executed action.
 */
export interface NpcActionProposal {
  readonly actionType: NpcActionType;
  readonly targetAgentId?: string;
  readonly establishmentId?: string;
  readonly parameters?: Record<string, unknown>;
  readonly reasoningContext?: string;
  readonly requestedAt: string;
}

/**
 * Complete context passed into an NpcCognitionProvider.
 */
export interface NpcCognitionContext {
  readonly perception: NpcPerception;
  readonly goal: NpcGoal;
  readonly memories: readonly NpcMemory[];
}

/**
 * Result returned by an NpcCognitionProvider.
 */
export interface NpcCognitionResult {
  readonly proposal: NpcActionProposal;
  readonly providerId: string;
  readonly modelUsed?: string;
  readonly rawResponse?: string;
  readonly latencyMs?: number;
}

/**
 * Replaceable cognition provider interface.
 * Decouples the World Core and runtime from specific AI vendors.
 */
export interface NpcCognitionProvider {
  readonly id: string;
  decideAction(context: NpcCognitionContext): Promise<NpcCognitionResult>;
}

/**
 * Status of an AI execution cycle.
 */
export type NpcAiCycleStatus =
  | 'executed'
  | 'noop'
  | 'rejected'
  | 'provider_failed'
  | 'invalid_proposal';

/**
 * Result of executing an AI cognition cycle in the runtime orchestrator.
 */
export interface NpcAiCycleResult {
  readonly cycleId: string;
  readonly agentId: string;
  readonly worldTime: string;
  readonly status: NpcAiCycleStatus;
  readonly perception: NpcPerception;
  readonly proposal?: NpcActionProposal;
  readonly commandDispatched?: {
    readonly commandName: string;
    readonly payload: Record<string, unknown>;
    readonly success: boolean;
    readonly error?: { code: string; message: string };
  };
  readonly error?: {
    readonly code: string;
    readonly message: string;
  };
  readonly durationMs: number;
}

/**
 * Diagnostic summary of the AI runtime.
 */
export interface NpcAiDiagnostics {
  readonly agentId: string;
  readonly providerId: string;
  readonly totalCycles: number;
  readonly lastCycle?: NpcAiCycleResult;
  readonly activeGoal: NpcGoal;
  readonly memoriesCount: number;
}
